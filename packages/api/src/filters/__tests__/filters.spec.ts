import {
  FilterManager,
  FilterBlockError,
  createPIIFilter,
  createModerationFilter,
  createDecoratorFilter,
  redactText,
  checkBlocked,
  redactBlocked,
} from '../index';

describe('Filter Middleware System', () => {
  describe('PII Redaction Filter', () => {
    it('redacts emails, phone numbers, and API keys correctly with redactText', () => {
      const rawText =
        'Contact me at support@librechat.ai or +1 (555) 123-4567. Key: sk-proj-1234567890abcdef1234567890abcdef.';
      const cleaned = redactText(rawText);

      expect(cleaned).toContain('[EMAIL_REDACTED]');
      expect(cleaned).toContain('[PHONE_REDACTED]');
      expect(cleaned).toContain('[API_KEY_REDACTED]');
      expect(cleaned).not.toContain('support@librechat.ai');
      expect(cleaned).not.toContain('123-4567');
      expect(cleaned).not.toContain('sk-proj-1234567890abcdef1234567890abcdef');
    });

    it('redacts PII in inlet payloads (text, prompt, messages)', async () => {
      const piiFilter = createPIIFilter();
      const payload = {
        text: 'Send bill to billing@corp.com',
        prompt: 'System prompt with contact test@domain.org',
        messages: [
          { role: 'user', content: 'Call 555-867-5309' },
          { role: 'assistant', content: 'Normal response' },
        ],
      };

      const result = await piiFilter.inlet!(payload, {});
      expect(result.text).toBe('Send bill to [EMAIL_REDACTED]');
      expect(result.prompt).toBe('System prompt with contact [EMAIL_REDACTED]');
      expect((result.messages as any[])[0].content).toBe('Call [PHONE_REDACTED]');
      expect((result.messages as any[])[1].content).toBe('Normal response');
    });

    it('redacts PII in outlet payloads', async () => {
      const piiFilter = createPIIFilter();
      const payload = {
        text: 'The leaked key is ghp_1234567890abcdef1234567890abcdef1234.',
      };

      const result = await piiFilter.outlet!(payload, {});
      expect(result.text).toBe('The leaked key is [API_KEY_REDACTED].');
    });
  });

  describe('Moderation Blocklist Filter', () => {
    it('blocks inlet text matching banned patterns with FilterBlockError', async () => {
      const modFilter = createModerationFilter({
        blockedTerms: ['\\bforbidden_term\\b', 'malicious_exploit'],
      });

      await expect(
        modFilter.inlet!({ text: 'This contains a forbidden_term here.' }, {}),
      ).rejects.toThrow(FilterBlockError);

      await expect(
        modFilter.inlet!({ text: 'Normal safe query' }, {}),
      ).resolves.toEqual({ text: 'Normal safe query' });
    });

    it('blocks inlet messages array matching banned patterns', async () => {
      const modFilter = createModerationFilter({
        blockedTerms: ['hack_attempt'],
      });

      await expect(
        modFilter.inlet!(
          {
            messages: [
              { role: 'user', content: 'execute hack_attempt now' },
            ],
          },
          {},
        ),
      ).rejects.toThrow(FilterBlockError);
    });

    it('redacts banned terms in outlet responses when action is redact', async () => {
      const modFilter = createModerationFilter({
        blockedTerms: ['classified_leak'],
        outletAction: 'redact',
      });

      const result = await modFilter.outlet!(
        { text: 'Here is the classified_leak detail.' },
        {},
      );
      expect(result.text).toBe('Here is the [REDACTED] detail.');
    });

    it('throws FilterBlockError in outlet when action is block', async () => {
      const modFilter = createModerationFilter({
        blockedTerms: ['secret_token'],
        outletAction: 'block',
      });

      await expect(
        modFilter.outlet!({ text: 'Output has secret_token' }, {}),
      ).rejects.toThrow(FilterBlockError);
    });
  });

  describe('Prompt & Response Decorator Filter', () => {
    it('injects prefix and suffix to inlet prompt and text', async () => {
      const decorator = createDecoratorFilter({
        promptPrefix: '[INSTRUCTION: Be concise] ',
        promptSuffix: ' [END INSTRUCTION]',
        responseSuffix: '\n\n---\n*Generated by LibreChat*',
      });

      const inletResult = await decorator.inlet!(
        { text: 'What is photosynthesis?' },
        {},
      );
      expect(inletResult.text).toBe(
        '[INSTRUCTION: Be concise] What is photosynthesis? [END INSTRUCTION]',
      );

      const outletResult = await decorator.outlet!(
        { text: 'Photosynthesis is the process...' },
        {},
      );
      expect(outletResult.text).toBe(
        'Photosynthesis is the process...\n\n---\n*Generated by LibreChat*',
      );
    });
  });

  describe('FilterManager', () => {
    it('manages filter lifecycle and sorts by priority', async () => {
      const manager = new FilterManager();

      const filterHigh = {
        id: 'high-priority',
        name: 'High Priority',
        priority: 10,
        inlet: async (payload: any) => ({
          ...payload,
          text: `[10:${payload.text}]`,
        }),
      };

      const filterLow = {
        id: 'low-priority',
        name: 'Low Priority',
        priority: 50,
        inlet: async (payload: any) => ({
          ...payload,
          text: `[50:${payload.text}]`,
        }),
      };

      // Register in reverse order
      manager.register(filterLow);
      manager.register(filterHigh);

      const result = await manager.applyInlet({ text: 'hello' });
      // Priority 10 runs first wrapping hello -> [10:hello], then priority 50 wraps -> [50:[10:hello]]
      expect(result.text).toBe('[50:[10:hello]]');

      // Test unregister
      manager.unregister('high-priority');
      const resultAfterRemoval = await manager.applyInlet({ text: 'hello' });
      expect(resultAfterRemoval.text).toBe('[50:hello]');
    });

    it('runs pipeline of PII redaction and decoration seamlessly', async () => {
      const manager = new FilterManager();
      manager.register(createPIIFilter());
      manager.register(
        createDecoratorFilter({
          responseSuffix: ' [CONFIDENTIAL]',
        }),
      );

      // Test combined inlet
      const inletResult = await manager.applyInlet({
        text: 'Contact admin@internal.net',
      });
      expect(inletResult.text).toBe('Contact [EMAIL_REDACTED]');

      // Test combined outlet
      const outletResult = await manager.applyOutlet({
        text: 'Your key is sk-1234567890abcdef1234567890abcdef',
      });
      expect(outletResult.text).toBe(
        'Your key is [API_KEY_REDACTED] [CONFIDENTIAL]',
      );
    });
  });
});
